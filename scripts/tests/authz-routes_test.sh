# expect_red NAME NEEDLE... -- GATE_ARGS...: the gate must exit non-zero and print every NEEDLE.
expect_red() {
  local name="$1"
  shift
  local needles=()
  while [ "$1" != "--" ]; do
    needles+=("$1")
    shift
  done
  shift
  local rc=0 out
  out="$("$gate" "$@" 2>&1)" || rc=$?
  local n
  if [ "$rc" -eq 0 ]; then
    ko "RED $name: gate passed but must fail"
    return
  fi
  for n in "${needles[@]}"; do
    if ! grep -qF -- "$n" <<<"$out"; then
      ko "RED $name: output lacks '$n' (rc=$rc, out=$out)"
      return
    fi
  done
  ok "RED: $name"
}

